"""
Pure Pursuit data collection on the Oschersleben centerline.

Each sample is (x, u), where u = [omega, a] is generated by a Pure Pursuit
tracking controller instead of the MPCC/CasADi solver.
"""

import argparse
import sys
import os
import numpy as np
from datetime import datetime
from pathlib import Path
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import yaml
import track

REPO_ROOT = Path(__file__).resolve().parents[2]
SCRIPT_DIR = str(Path(__file__).resolve().parent)
sys.path = [path for path in sys.path if path != SCRIPT_DIR]
sys.path.insert(0, str(REPO_ROOT))

MPCC_CONFIG = REPO_ROOT / "model" / "auto_car" / "mpcc_parameter.yaml"

from model.auto_car.auto_car import f_phys

with open(MPCC_CONFIG, 'r') as file:
    param = yaml.safe_load(file)


A_MAX = float(param["A_MAX"])
A_MIN = float(param["A_MIN"])
DATA_DIR = param["DATA_DIR"]
DT = float(param["DT"])
N_DATA = int(param["N_DATA"])
OMEGA_MAX = float(param["OMEGA_MAX"])
OMEGA_MIN = float(param["OMEGA_MIN"])
V_MAX = float(param["V_MAX"])
V_MIN = float(param["V_MIN"])

FIG_DIR = REPO_ROOT / "data" / "training"

v_int = V_MAX / 2

PP_LOOKAHEAD_MIN = 1.0
PP_LOOKAHEAD_GAIN = 0.1
PP_LOOKAHEAD_MAX = 3.0
PP_CURVE_LOOKAHEAD_MIN = 0.8
PP_CURVE_LOOKAHEAD_GAIN = 2.0
CURVATURE_DS = 0.6
CURVE_PREVIEW_DISTANCE = 15.0
CURVE_PREVIEW_POINTS = 10
CURVE_SPEED_MARGIN = 0.9
INITIAL_LATERAL_RANGE = 0.1


def build_v_max_schedule(n_data: int) -> np.ndarray:
    steps = np.random.uniform(low=-0.495, high=0.5, size=n_data - 1)

    cum = np.zeros(len(steps) + 1)
    cum[0] = v_int

    for i in range(len(steps)):
        temp = cum[i] + steps[i]
        if temp >= V_MAX:
            cum[i + 1] = V_MAX
        elif temp <= V_MIN:
            cum[i + 1] = V_MIN
        else:
            cum[i + 1] = temp

    return np.clip(cum, V_MIN, V_MAX)


def wrap_angle_pi(angle: float) -> float:
    return float((angle + np.pi) % (2.0 * np.pi) - np.pi)


def sample_state(rng: np.random.Generator, v_max: float = V_MAX) -> np.ndarray:
    """Sample 4D state [X, Y, phi, v] near the reference path."""
    p = 0.0
    xc, yc = track.centerline_xy(np.array([p]))
    phi_ref = float(track.tangent_angle(np.array([p]))[0])
    lateral = rng.uniform(-INITIAL_LATERAL_RANGE, INITIAL_LATERAL_RANGE)
    heading_error = rng.uniform(-0.1, 0.1)
    nx = -np.sin(phi_ref)
    ny = np.cos(phi_ref)
    x = np.array(
        [
            float(xc[0] + lateral * nx),
            float(yc[0] + lateral * ny),
            phi_ref + heading_error,
            min(v_int, v_max),
        ],
        dtype=np.float64,
    )
    return x


def progress_delta(p_now: float, p_prev: float) -> float:
    """Forward progress increment on a closed track, robust to lap wrap."""
    delta = float(p_now - p_prev)
    if delta < -0.5 * track.p_max:
        delta += track.p_max
    elif delta > 0.5 * track.p_max:
        delta -= track.p_max
    return max(delta, 0.0)


def path_curvature(p: float, ds: float = CURVATURE_DS) -> float:
    """Numerically estimate centerline curvature d(phi_ref) / ds."""
    phi_plus = float(track.tangent_angle(np.array([(p + ds) % track.p_max]))[0])
    phi_minus = float(track.tangent_angle(np.array([(p - ds) % track.p_max]))[0])
    return wrap_angle_pi(phi_plus - phi_minus) / (2.0 * ds)


def preview_curvature(p_now: float) -> float:
    """Maximum absolute curvature over the near-future centerline preview."""
    offsets = np.linspace(0.0, CURVE_PREVIEW_DISTANCE, CURVE_PREVIEW_POINTS)
    curvatures = [abs(path_curvature((p_now + offset) % track.p_max)) for offset in offsets]
    return float(max(curvatures))


def curvature_speed_limit(abs_curvature: float) -> float:
    """Speed that keeps v * curvature inside the yaw-rate input bound."""
    if abs_curvature <= 1e-6:
        return V_MAX
    return float(np.clip(CURVE_SPEED_MARGIN * OMEGA_MAX / abs_curvature, V_MIN, V_MAX))


def pure_pursuit_control(x_state: np.ndarray, p_now: float, v_max: float) -> np.ndarray:
    """Return bounded [omega, a] for centerline Pure Pursuit tracking."""
    X, Y, phi, v = x_state
    abs_curvature = preview_curvature(p_now)
    base_lookahead = np.clip(
        PP_LOOKAHEAD_MIN + PP_LOOKAHEAD_GAIN * max(float(v), 0.0),
        PP_LOOKAHEAD_MIN,
        PP_LOOKAHEAD_MAX,
    )
    lookahead = np.clip(
        base_lookahead / (1.0 + PP_CURVE_LOOKAHEAD_GAIN * abs_curvature),
        PP_CURVE_LOOKAHEAD_MIN,
        PP_LOOKAHEAD_MAX,
    )
    target_p = (float(p_now) + float(lookahead)) % track.p_max
    target_x, target_y = track.centerline_xy(np.array([target_p]))

    target_heading = np.arctan2(float(target_y[0]) - Y, float(target_x[0]) - X)
    alpha = wrap_angle_pi(target_heading - phi)
    omega_cmd = float(v) * 2.0 * np.sin(alpha) / max(float(lookahead), 1e-6)
    omega = np.clip(omega_cmd, OMEGA_MIN, OMEGA_MAX)

    target_v = np.clip(min(float(v_max), curvature_speed_limit(abs_curvature)), V_MIN, V_MAX)
    a_cmd = (target_v - float(v)) / max(DT, 1e-6)
    a = np.clip(a_cmd, A_MIN, A_MAX)

    return np.array([omega, a], dtype=np.float64)


def step_dynamics(x_state: np.ndarray, u: np.ndarray) -> np.ndarray:
    x_next = np.asarray(f_phys(np.asarray(x_state), np.asarray(u)), dtype=np.float64)
    x_next[2] = wrap_angle_pi(float(x_next[2]))
    x_next[3] = np.clip(x_next[3], V_MIN, V_MAX)
    return x_next


def plot_collected_trajectory(xs, lap_sample_counts, output_dir: str = FIG_DIR):
    """Plot the collected Pure Pursuit trajectory on the Oschersleben track."""
    if plt is None:
        return None

    os.makedirs(output_dir, exist_ok=True)
    states = np.asarray(xs, dtype=float)
    if states.size == 0:
        return None

    center, left, right = track.border_lines(n_pts=800)

    fig, ax = plt.subplots(figsize=(10, 5))
    ax.plot(center[:, 0], center[:, 1], "r--", lw=1.0, label="Centerline")
    ax.plot(left[:, 0], left[:, 1], "k-", lw=1.1, label="Border")
    ax.plot(right[:, 0], right[:, 1], "k-", lw=1.0)
    ax.plot(states[:, 0], states[:, 1], "b-", lw=0.8, label="Pure Pursuit trajectory")

    start = 0
    for lap_idx, count in enumerate(lap_sample_counts):
        if count <= 0:
            continue
        idx = min(start, len(states) - 1)
        ax.plot(
            states[idx, 0],
            states[idx, 1],
            "o",
            ms=3.5,
            label="Lap start" if lap_idx == 0 else None,
        )
        start += int(count)

    ax.set_xlabel("X [m]")
    ax.set_ylabel("Y [m]")
    ax.set_title("Pure Pursuit Collected Trajectory")
    ax.legend()
    ax.set_aspect("equal")
    fig.tight_layout()

    path = os.path.join(output_dir, f"collect_trajectory_PP_N={len(states)}.pdf")
    fig.savefig(path)
    plt.close(fig)
    return path


def collect_all_laps(start_state: np.ndarray, n_data: int = N_DATA):
    """Collect n_data samples from one continuous Pure Pursuit trajectory."""
    x_state = np.asarray(start_state, dtype=np.float64).copy()
    phi_unwrapped = float(x_state[2])
    v_max_schedule = build_v_max_schedule(n_data)

    p_prev = track.find_progress(
        float(x_state[0]), float(x_state[1]), 0.0, n_search=1, n_grid=401
    )

    lap_progress = 0.0
    next_lap_progress = track.p_max
    current_lap_count = 0

    xs, u0 = [], []
    lap_sample_counts = []

    for i in range(n_data):
        current_v_max = float(v_max_schedule[i])

        p_now = track.find_progress(float(x_state[0]), float(x_state[1]), p_prev, n_search=5, n_grid=101)
        lap_progress += progress_delta(p_now, p_prev)
        p_prev = p_now

        while lap_progress >= next_lap_progress and current_lap_count > 0:
            lap_sample_counts.append(current_lap_count)
            current_lap_count = 0
            next_lap_progress += track.p_max

        u = pure_pursuit_control(x_state, p_now, current_v_max)
        u[0] += np.clip(np.random.rand(), -1, 1)

        if i % 100 == 0:
            print(f"Collected {i} data after {len(lap_sample_counts)} laps | " f"V_MAX = {current_v_max:.2f} | v = {x_state[3]:.2f}")

        x_sample    = x_state.copy()
        x_sample[2] = phi_unwrapped
        xs.append(x_sample.astype(np.float32))
        u0.append(u.astype(np.float32))
        current_lap_count += 1

        x_state = step_dynamics(x_state, u)
        phi_unwrapped += DT * float(u[0])

    if current_lap_count > 0:
        lap_sample_counts.append(current_lap_count)

    return xs, u0, lap_sample_counts, DT


def generate_dataset(
    n_data: int = N_DATA,
    seed: int = 0,
    output_dir: str = DATA_DIR,
    max_starting_points: int = 10,
):
    _ = max_starting_points

    os.makedirs(output_dir, exist_ok=True)

    np.random.seed(seed)
    rng = np.random.default_rng(seed)

    start_state = sample_state(rng, V_MAX)
    xs, u0, lap_sample_counts, DT = collect_all_laps(start_state, n_data)

    print(f"{len(u0)} samples across {len(lap_sample_counts)} lap segments")

    if not u0:
        raise RuntimeError("No Pure Pursuit labels were generated")
    if len(u0) < n_data:
        raise RuntimeError(f"Only generated {len(u0)} labels; requested {n_data}")

    stamp = datetime.now().strftime("%m%d%H%M")
    count = len(u0)
    path = os.path.join(output_dir, f"AC_PP_{count}_{stamp}.npz")
    np.savez(
        path,
        x = np.asarray(xs, dtype=np.float32),
        u = np.asarray(u0, dtype=np.float32),
        sample_time = np.asarray(DT, dtype=np.float32),
        lap_sample_counts = np.asarray(lap_sample_counts, dtype=np.int32),
    )
    print(f"Saved {count} samples to {path}")
    plot_collected_trajectory(xs, lap_sample_counts)
    return path


def parse_args():
    parser = argparse.ArgumentParser(description="Generate Pure Pursuit training data.")
    parser.add_argument("--n-data", type=int, default=N_DATA)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--output-dir", default=DATA_DIR)
    parser.add_argument("--max-starting-points", type=int, default=10_000)
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    generate_dataset(args.n_data, args.seed, args.output_dir, args.max_starting_points)
